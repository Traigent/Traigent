"""Write the SDK egress baseline report.  Run by hand, never by a test.

PYTHONPATH=<worktree> python -m tests.egress_canary.report <out.md>
"""

from __future__ import annotations

import sys
import tempfile
from collections import Counter, defaultdict
from pathlib import Path

from .canaries import CANARIES, Leak, distinct_pairs, forms
from .harness import CapturedRequest
from .scenario import ScenarioResult, run_scenario


def render_report(result: ScenarioResult, pinned: int | None = None) -> str:
    pairs = sorted(distinct_pairs(result.leaks))
    by_pair: dict[tuple[str, str], list[Leak]] = defaultdict(list)
    for leak in result.leaks:
        by_pair[leak.pair].append(leak)

    lines: list[str] = []
    add = lines.append
    add("# SDK egress baseline (Phase 1, content-less optimization)")
    add("")
    add(
        "Generated by `python -m tests.egress_canary.report` from the Traigent SDK "
        "worktree. Measures what the SDK *sends*; backend responses are a "
        "schema-plausible fake and are not searched."
    )
    add("")
    add(f"- distinct (route, canary kind) leak pairs: **{len(pairs)}**")
    if pinned is not None:
        add(f"- pinned in the ratchet test: {pinned}")
    add(
        f"- captured requests: {len(result.requests)} across {len(result.routes)} routes"
    )
    add(
        f"- canary kinds planted: {len(CANARIES)}; encoded forms searched per canary: {len(forms(next(iter(CANARIES.values()))))}"
    )
    add(
        f"- optimize() run: source={result.result_source!r}, error={result.optimization_error!r}"
    )
    add(f"- non-captured socket attempts: {len(result.guard_violations)}")
    add("")
    add("## Leaks by route")
    add("")
    add("| Route | Canary kind | Locations | Forms | Example field path |")
    add("|---|---|---|---|---|")
    for route, kind in pairs:
        items = by_pair[(route, kind)]
        locs = ", ".join(sorted({i.location for i in items}))
        frm = ", ".join(sorted({i.form for i in items}))
        example = next((i.field_path for i in items if i.field_path), "")
        add(f"| `{route}` | {kind} | {locs} | {frm} | `{example}` |")
    add("")
    add("## Leaks by canary kind")
    add("")
    kind_counts = Counter(kind for _, kind in pairs)
    for kind in CANARIES:
        n = kind_counts.get(kind, 0)
        routes = sorted({r for r, k in pairs if k == kind})
        add(
            f"- `{kind}`: {n} route(s)"
            + (f" — {', '.join(routes)}" if routes else " — not seen on the wire")
        )
    add("")
    add("## Routes captured")
    add("")
    counts: Counter[tuple[str, str]] = Counter()
    for req in result.requests:
        counts[(req.route, req.transport)] += 1
    add("| Route | Transport | Requests |")
    add("|---|---|---|")
    for (route, transport), n in sorted(counts.items()):
        add(f"| `{route}` | {transport} | {n} |")
    add("")
    add("## Direct-path exercisers")
    add("")
    for name, err in result.exerciser_outcomes.items():
        add(f"- `{name}`: {'ran' if err is None else 'FAILED: ' + err}")
    if result.unhandled_routes:
        add("")
        add(
            "Routes the fake backend had no handler for: "
            + ", ".join(f"`{r}`" for r in result.unhandled_routes)
        )
    add("")
    add("## Notes")
    add("")
    add(
        "- Credentials are dropped (Authorization, X-API-Key, X-Service-Key, Cookie headers) or redacted (`api_key`/`token` JSON body values) at capture; they never reach this report."
    )
    add(
        "- A pair is a leak when any encoded form of a canary (raw, lowercase, slug, URL-encoded, base64, hex, unsalted sha256/md5, sha256 prefix) appears in path, query, header, or body."
    )
    add(
        "- Exercisers pass canaries directly as arguments to cloud-client entry points that a default `optimize()` run does not reach; a clean exerciser proves the SDK transmits the value as given, not that real callers pass it."
    )
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    if len(argv) != 2:
        print("usage: python -m tests.egress_canary.report <out.md>", file=sys.stderr)
        return 2
    from .pins import PINNED_LEAK_PAIRS

    with tempfile.TemporaryDirectory() as tmp:
        result = run_scenario(Path(tmp))
    Path(argv[1]).write_text(render_report(result, PINNED_LEAK_PAIRS), encoding="utf-8")
    print(f"wrote {argv[1]}: {len(distinct_pairs(result.leaks))} leak pairs")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))


__all__ = ["CapturedRequest", "main", "render_report"]
