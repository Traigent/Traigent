def _strict_closed(value: Any, depth: int = 0) -> None:
    """Raise ``_Drop`` unless every key is identifier-shaped and every string leaf is an
    identifier or digest (numbers, booleans and null are closed)."""
    if depth > MAX_DEPTH + 8:
        raise _Drop
    if value is None or isinstance(value, bool):
        return
    if _is_number(value):
        if not math.isfinite(value):
            raise _Drop
        return
    if isinstance(value, str):
        if ID_RE.fullmatch(value) or SHA256_RE.fullmatch(value):
            return
        raise _Drop
    if isinstance(value, (list, tuple)):
        for item in value:
            _strict_closed(item, depth + 1)
        return
    if isinstance(value, dict):
        for key, item in value.items():
            if not isinstance(key, str) or ID_RE.fullmatch(key) is None:
                raise _Drop
            _strict_closed(item, depth + 1)
        return
    raise _Drop


def is_closed_value(value: Any) -> bool:
    """True when ``value`` holds only identifier keys and identifier/digest/number leaves."""
    try:
        _strict_closed(value)
    except _Drop:
        return False
    return True


def assert_closed_body(
    payload: Any, operation: str, *, explicit: bool | Policy | None = None
) -> None:
    """Mode on: refuse (locally, before any transport call) a request body that carries
    anything beyond closed values. Nothing is rewritten; mode off: no-op."""
    if is_active(explicit) and not is_closed_value(payload):
        raise OptimizationOnlyRefusal(operation)


def assert_closed_json_bytes(
    content: bytes | str, operation: str, *, explicit: bool | Policy | None = None
) -> None:
    """``assert_closed_body`` for an already-serialized JSON body (unparseable is refused)."""
    if not is_active(explicit):
        return
    try:
        parsed = json.loads(content)
    except (TypeError, ValueError):
        raise OptimizationOnlyRefusal(operation) from None
    assert_closed_body(parsed, operation, explicit=explicit)


def assert_closed_ids(
    operation: str, *values: Any, explicit: bool | Policy | None = None
) -> None:
    """Mode on: every non-None value (path/query parameter) must be identifier-shaped."""
    if not is_active(explicit):
        return
    for value in values:
        if value is not None and not (
            isinstance(value, str) and ID_RE.fullmatch(value)
        ):
            raise OptimizationOnlyRefusal(operation)


