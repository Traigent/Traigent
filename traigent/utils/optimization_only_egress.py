ENV_VAR = "TRAIGENT_OPTIMIZATION_ONLY"
OPTIMIZATION_ONLY_CODE = "optimization_only"
OPTIMIZATION_ONLY_MESSAGE = (
    "This workspace is limited to optimization; this operation is not available."
)

_TRUTHY = frozenset({"1", "true", "yes", "on"})
_FALSY = frozenset({"0", "false", "no", "off"})


class OptimizationOnlyConfigError(ValueError):
    """``TRAIGENT_OPTIMIZATION_ONLY`` (or the explicit argument) is not a recognised value."""


class OptimizationOnlyRefusal(RuntimeError):
    """An operation the server refuses for ``optimization_only`` workspaces, refused locally.

    Raised BEFORE any transport call. Carries the operation name only, never request data.
    """

    error_code = OPTIMIZATION_ONLY_CODE

    def __init__(self, operation: str) -> None:
        self.operation = operation
        super().__init__(f"{OPTIMIZATION_ONLY_MESSAGE} (operation: {operation})")


_latch_lock = threading.Lock()
#: Credential scopes (see :func:`credential_scope`) that received a closed refusal.
_latched_scopes: set[str] = set()


def parse_flag(raw: Any, *, source: str = ENV_VAR) -> bool | None:
    """Parse an on/off value. ``None`` or blank means unset; anything unrecognised raises."""
    if raw is None:
        return None
    if isinstance(raw, bool):
        return raw
    if isinstance(raw, str):
        text = raw.strip().lower()
        if not text:
            return None
        if text in _TRUTHY:
            return True
        if text in _FALSY:
            return False
    raise OptimizationOnlyConfigError(
        f"{source} must be one of 1/true/yes/on or 0/false/no/off"
    )


def env_setting(environ: Mapping[str, str] | None = None) -> bool | None:
    """The environment's opinion: True, False, or None when unset. Invalid raises."""
    env = os.environ if environ is None else environ
    return parse_flag(env.get(ENV_VAR))


#: Precedence of the credential that actually authenticates a request. The backend tries
#: JWT (``Authorization: Bearer``) before the API key (``src/security/unified_auth.py``
#: ``authenticate``: ``[AuthMethod.JWT, AuthMethod.API_KEY]``), so the scope follows it.
_CREDENTIAL_HEADERS = ("authorization", "x-api-key", "x-service-key")


def normalised_origin(url: Any) -> str:
    """``scheme://host[:port]``: lowercase host, default port dropped, so equivalent
    spellings of one origin share a latch."""
    try:
        parts = urlsplit(str(url))
        scheme = parts.scheme.lower()
        host = (parts.hostname or "").lower().rstrip(".")
        port = parts.port
    except ValueError:
        return ""
    try:
        address = ipaddress.ip_address(host)
    except ValueError:
        address = None
    if address is not None:
        if isinstance(address, ipaddress.IPv6Address) and address.ipv4_mapped:
            address = address.ipv4_mapped  # ::ffff:1.2.3.4 is the IPv4 address
        host = f"[{address}]" if address.version == 6 else str(address)
    elif ":" in host:
        host = f"[{host}]"
    default = {"https": 443, "http": 80}.get(scheme)
    suffix = f":{port}" if port and port != default else ""
    return f"{scheme}://{host}{suffix}"


def credential_scope(url: Any, headers: Any = None) -> str | None:
    """Opaque key for "this backend origin + this credential", or None without a credential.

    The key is ``origin|sha256(credential headers)``; the raw credential is never stored or
    returned. Server-derived policy (a closed ``403 optimization_only``) is bound to this key,
    so one tenant's refusal cannot restrict a client using another credential.
    """
    if not isinstance(headers, Mapping):
        return None
    lowered = {str(k).lower(): v for k, v in headers.items()}
    material = ""
    for (
        name
    ) in _CREDENTIAL_HEADERS:  # priority order: the first credential present wins
        value = lowered.get(name)
        if isinstance(value, str) and value.strip():
            text = value.strip()
            if text.lower().startswith("bearer "):
                text = text[7:].strip()
            material = f"{name}:{text}"
            break
    if not material:
        return None
    origin = normalised_origin(url)
    digest = hashlib.sha256(material.encode("utf-8")).hexdigest()
    return f"{origin}|{digest}"


@dataclass(frozen=True)
class Policy:
    """The effective policy inputs of one send: explicit setting and credential scope."""

    explicit: bool | None = None
    scope: str | None = None


def _client_url(client: Any) -> str:
    for owner, names in (
        (getattr(client, "backend_config", None), ("api_base_url", "backend_base_url")),
        (client, ("api_base_url", "base_url")),
    ):
        for name in names:
            value = getattr(owner, name, None) if owner is not None else None
            if isinstance(value, str) and value:
                return value
    return ""


def scope_required(explicit: bool | None) -> bool:
    """Fast path: a credential scope matters only if some scope is latched and the client
    has not opted in outright. Otherwise nothing is resolved, hashed or awaited."""
    return bool(_latched_scopes) and explicit is not True


def _configured_headers(client: Any) -> Mapping[str, str] | None:
    """Credential headers of the client's CONFIGURED credential (no network, no refresh)."""
    auth_manager = getattr(client, "auth_manager", None)
    for owner in (
        getattr(client, "auth", None),
        getattr(auth_manager, "auth", None),
        auth_manager,
    ):
        method = getattr(owner, "configured_credential_headers", None)
        if callable(method):
            try:
                found = method()
            except Exception:  # noqa: BLE001 - silent-ok: unattributable, no scope
                continue
            if isinstance(found, Mapping) and found:
                return found
    return None


def policy_of(client: Any, headers: Any = None, url: Any = None) -> Policy:
    """THE resolver: effective policy for a send by ``client``.

    ``headers`` are the final request headers when the caller has them; otherwise the scope
    comes from the client's configured credential, so no call site can forget it.
    """
    explicit = explicit_of(client)
    if not scope_required(explicit):
        return Policy(explicit, None)
    target = url if url else _client_url(client)
    scope = credential_scope(target, headers)
    if scope is None:
        scope = credential_scope(target, _configured_headers(client))
    return Policy(explicit, scope)


def policy_from_headers(
    url: Any, headers: Any = None, explicit: bool | None = None
) -> Policy:
    """Resolver for senders that are not SDK clients (economics, plan, runtime, sync, traces
    ...): the headers they send (or the credential they hold, as headers) fix the scope."""
    if not scope_required(explicit):
        return Policy(explicit, None)
    return Policy(explicit, credential_scope(url, headers))


def policy_from_environment(url: Any, explicit: bool | None = None) -> Policy:
    """Resolver for senders that carry no credential of their own: the process's configured
    API key (``TRAIGENT_API_KEY`` / credential store) names the scope."""
    if not scope_required(explicit):
        return Policy(explicit, None)
    try:
        from traigent.utils.env_config import get_api_key

        key = get_api_key("traigent")
    except Exception:  # noqa: BLE001 - silent-ok: no configured credential, no scope
        key = None
    return Policy(explicit, credential_scope(url, {"X-API-Key": key} if key else None))


def latched_origins() -> set[str]:
    """Origins of every latched credential scope (``origin|fingerprint`` keys)."""
    with _latch_lock:
        return {scope.split("|", 1)[0] for scope in _latched_scopes}


def latch_on(scope: str | None) -> None:
    """Pin the mode on for ONE credential scope (a closed ``403 optimization_only``).

    ``None`` (a response with no credential to attribute it to) latches nothing.
    """
    if scope is None:
        return
    with _latch_lock:
        _latched_scopes.add(scope)


def is_latched(scope: str | None = None) -> bool:
    if scope is None:
        return False
    with _latch_lock:
        return scope in _latched_scopes


def reset_latch() -> None:
    """Test hook: clear every latch and the per-session objective registry."""
    with _latch_lock:
        _latched_scopes.clear()
    with _objectives_lock:
        _session_objectives.clear()


def is_active(explicit: bool | Policy | None = None, scope: str | None = None) -> bool:
    """True when the SDK must behave as an ``optimization_only`` client.

    Precedence: a refusal latched for THIS credential scope always wins; otherwise an
    explicit argument beats the environment; unset means legacy behaviour (opt-in).
    ``explicit`` may be a :class:`Policy` carrying both inputs.
    """
    if isinstance(explicit, Policy):
        scope = explicit.scope if scope is None else scope
        explicit = explicit.explicit
    if scope is not None and is_latched(scope):
        return True
    explicit_value = parse_flag(explicit, source="optimization_only")
    if explicit_value is not None:
        return explicit_value
    return bool(env_setting())


def is_closed_refusal(status: int | None, body: Any) -> bool:
    """True for the server's closed ``403 {"error_code": "optimization_only"}`` answer."""
    if status != 403:
        return False
    if isinstance(body, (bytes, bytearray)):
        try:
            body = bytes(body).decode("utf-8")
        except UnicodeDecodeError:
            return False
    if isinstance(body, str):
        try:
            body = json.loads(body)
        except ValueError:
            return False
    if not isinstance(body, dict):
        return False
    code = body.get("error_code")
    if not isinstance(code, str):
        code = body.get("error")
    return isinstance(code, str) and code.strip().lower() == OPTIMIZATION_ONLY_CODE


def note_response(status: int | None, body: Any, scope: str | None = None) -> bool:
    """Latch the mode on for ``scope`` when a response is the closed refusal.

    Returns True when the response was the closed refusal (whether or not it could be
    attributed to a credential scope).
    """
    if is_closed_refusal(status, body):
        latch_on(scope)
        return True
    return False


def note_key_validation(body: Any, scope: str | None = None) -> bool:
    """Latch the mode on for ``scope`` when a 2xx ``/keys/validate`` body says so.

    Only the exact field ``optimization_only`` holding the JSON boolean ``true`` counts
    (``"true"``, ``1`` and absent/false do nothing). It never un-latches and ignores any
    explicit client setting, like the closed 403 latch. Returns True when latched.
    """
    if scope is None or not isinstance(body, dict):
        return False
    if body.get("valid") is not True or body.get("optimization_only") is not True:
        return False
    latch_on(scope)
    return True


# ---- per-session declared objectives (objective-aware metric rules need them) -----------

_MAX_TRACKED_SESSIONS = 1024
_objectives_lock = threading.Lock()
_session_objectives: OrderedDict[str, tuple[str, ...]] = OrderedDict()


def register_session_objectives(session_id: Any, objectives: Any) -> None:
    """Remember a session's declared objective names for later results projection.

    ``objectives`` may be the raw objectives value or an iterable of metric names. A session
    this process did not create (resumed elsewhere) has no entry, so only the standard metric
    vocabulary survives projection for it: that can drop a declared custom metric the server
    would have kept, but never sends one it would drop.
    """
    if not isinstance(session_id, str) or not session_id:
        return
    names = declared_metric_names(objectives)
    with _objectives_lock:
        _session_objectives[session_id] = tuple(names)
        _session_objectives.move_to_end(session_id)
        while len(_session_objectives) > _MAX_TRACKED_SESSIONS:
            _session_objectives.popitem(last=False)


def declared_for(session_id: Any) -> tuple[str, ...]:
    if not isinstance(session_id, str):
        return ()
    with _objectives_lock:
        return _session_objectives.get(session_id, ())


def session_id_from_url(url: Any) -> str | None:
    """``.../sessions/<id>/...`` -> ``<id>`` (None when the URL has no session segment)."""
    parts = str(url).split("?", 1)[0].split("/")
    for index, part in enumerate(parts[:-1]):
        if part == "sessions" and parts[index + 1]:
            return parts[index + 1]
    return None


# ---- additional pure pieces: closed pass-through, example-content detection ---------------

_METADATA_SCAN_MAX_DEPTH = 8
_DIGEST_KEY_SUFFIXES = ("_sha256", "_digest", "_hash")
_HEX_RE = re.compile(r"[0-9a-fA-F]{16,128}")


def request_embeds_example_content(body: Any) -> bool:
    """True when a body carries dataset/example content (non-empty ``examples``), at the top
    level or inside any ``example_sets[]`` item. Port of the backend's shape check."""
    if not isinstance(body, dict):
        return False
    if body.get("examples"):
        return True
    example_sets = body.get("example_sets")
    if isinstance(example_sets, list):
        return any(
            isinstance(i, dict) and bool(i.get("examples")) for i in example_sets
        )
    return False


def _is_digest_value(value: Any) -> bool:
    if isinstance(value, str):
        return _HEX_RE.fullmatch(value) is not None
    if isinstance(value, (list, tuple)):
        return all(
            isinstance(v, str) and _HEX_RE.fullmatch(v) is not None for v in value
        )
    return False


def _has_text_leaf(value: Any, depth: int = 0) -> bool:
    if depth > _METADATA_SCAN_MAX_DEPTH:
        return True
    if isinstance(value, str):
        return bool(value.strip())
    if isinstance(value, dict):
        for k, v in value.items():
            if (
                isinstance(k, str)
                and k.endswith(_DIGEST_KEY_SUFFIXES)
                and _is_digest_value(v)
            ):
                continue
            if _has_text_leaf(v, depth + 1):
                return True
        return False
    if isinstance(value, (list, tuple)):
        return any(_has_text_leaf(v, depth + 1) for v in value)
    return False


def metadata_embeds_example_content(value: Any, depth: int = 0) -> bool:
    """True when metadata nests an ``examples`` list holding any non-empty text (port)."""
    if depth > _METADATA_SCAN_MAX_DEPTH:
        return True
    if isinstance(value, dict):
        for key, item in value.items():
            if key == "examples" and _has_text_leaf(item):
                return True
            if metadata_embeds_example_content(item, depth + 1):
                return True
    elif isinstance(value, (list, tuple)):
        return any(metadata_embeds_example_content(v, depth + 1) for v in value)
    return False


def _payload_embeds_examples(payload: Any) -> bool:
    if request_embeds_example_content(payload):
        return True
    if isinstance(payload, dict):
        # the server scans the session ``metadata`` (not knob names or other keys)
        return metadata_embeds_example_content(payload.get("metadata"))
    return False


def _closed_passthrough(value: Any) -> Any:
    """Keep a top-level scalar only when it cannot carry free text; else raise ``_Drop``."""
    if value is None or isinstance(value, bool):
        return value
    if _is_number(value):
        if not math.isfinite(value) or abs(value) > MAX_NUM:
            raise _Drop
        return value
    if isinstance(value, str) and ID_RE.fullmatch(value):
        return value
    raise _Drop


