def _measures_spec(value: Any, ctx: _Ctx, depth: int) -> Any:
    """``measures``: a flat metrics map, or a list of per-example rows."""
    if isinstance(value, list):
        rows: list[Any] = []
        for item in value[:1000]:
            if not isinstance(item, dict):
                continue
            if "example_id" not in item:
                # flat per-example metrics dict (legacy list-of-flat-dicts shape)
                try:
                    rows.append(s_metric_map()(item, ctx, depth + 1))
                except _Drop:
                    pass
                continue
            row = _MEASURE_ROW(item, ctx, depth + 1)
            if "example_id" not in row:
                raise MetadataContractViolation
            rows.append(row)
        return rows
    if isinstance(value, dict):
        if "metrics" in value:
            return s_obj({"metrics": s_metric_map(), "execution_time": s_num(0)})(
                value, ctx, depth
            )
        return s_metric_map()(value, ctx, depth)
    raise _Drop


def _error_code(value: Any) -> str | None:
    if not isinstance(value, str) or not value.strip():
        return None
    return value if value in WIRE_ERROR_CODES else DEFAULT_ERROR_CODE


def _check_contract_version(container: Any) -> None:
    if isinstance(container, dict) and CONTRACT_VERSION_KEY in container:
        version = container[CONTRACT_VERSION_KEY]
        if isinstance(version, bool) or version != METADATA_CONTRACT_VERSION:
            raise MetadataContractViolation


def _json_size(value: Any) -> int:
    try:
        return len(json.dumps(value, separators=(",", ":"), default=str))
    except (TypeError, ValueError):
        raise MetadataContractViolation from None


def _size_ok(value: Any, limit: int, *, identity: bool = False) -> None:
    """Bound the projected size. A content-identity object has its own, larger cap (sized for
    2,000 inline members) applied wherever it appears; the remainder keeps ``limit``."""
    if identity:
        if _json_size(value) > MAX_IDENTITY_BYTES:
            raise MetadataContractViolation
        return
    rest = value
    if isinstance(value, dict):
        rest = dict(value)
        holders = [rest]
        if isinstance(rest.get("metadata"), dict):
            rest["metadata"] = dict(rest["metadata"])
            holders.append(rest["metadata"])
        for holder in holders:
            if "content_identity" in holder:
                if _json_size(holder.pop("content_identity")) > MAX_IDENTITY_BYTES:
                    raise MetadataContractViolation
    if _json_size(rest) > limit:
        raise MetadataContractViolation


def _run(
    spec: Spec,
    value: Any,
    ctx: _Ctx,
    *,
    limit: int = MAX_METADATA_BYTES,
    identity: bool = False,
) -> Any:
    """Project ``value`` through ``spec``; a non-fitting top level becomes ``{}``/dropped."""
    _check_contract_version(value)
    try:
        projected = spec(value, ctx, 0)
    except _Drop:
        raise MetadataContractViolation from None
    _size_ok(projected, limit, identity=identity)
    return projected


def _optional(
    spec: Spec,
    value: Any,
    ctx: _Ctx,
    *,
    limit: int = MAX_METADATA_BYTES,
    identity: bool = False,
) -> Any:
    """Like :func:`_run` for ``None``/absent-tolerant optional containers."""
    if value is None:
        return None
    return _run(spec, value, ctx, limit=limit, identity=identity)


def declared_metric_names(objectives: Any) -> list[str]:
    """Metric names declared by a session's objectives (strings or ``metric``/``name`` dicts)."""
    names: list[str] = []
    if isinstance(objectives, dict):
        return [k for k in objectives if isinstance(k, str)]
    if isinstance(objectives, (list, tuple)):
        for objective in objectives:
            if isinstance(objective, str):
                names.append(objective)
            elif isinstance(objective, dict):
                metric = objective.get("metric") or objective.get("name")
                if isinstance(metric, str):
                    names.append(metric)
    return names


