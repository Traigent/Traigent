_CONSTRAINT_EXPR_MAX = 512


def expression_is_closed(expr: Any) -> bool:
    """A constraint expression is accepted for a flagged tenant only when it carries no comment
    and every string literal is identifier-shaped (so it cannot hold free text)."""
    if (
        not isinstance(expr, str)
        or not expr.strip()
        or len(expr) > _CONSTRAINT_EXPR_MAX
    ):
        return False
    try:
        for tok in tokenize.generate_tokens(io.StringIO(expr).readline):
            if tok.type == tokenize.COMMENT:
                return False
            if tok.type == tokenize.STRING:
                literal = ast.literal_eval(tok.string)
                if not isinstance(literal, str) or ID_RE.fullmatch(literal) is None:
                    return False
            elif tok.type in _FSTRING_TOKENS:
                return False
    except (tokenize.TokenError, SyntaxError, ValueError):
        return False
    return "#" not in expr  # '#' outside a literal would have been a COMMENT token


_FSTRING_TOKENS = {
    getattr(tokenize, name)
    for name in ("FSTRING_START", "FSTRING_MIDDLE", "FSTRING_END")
    if hasattr(tokenize, name)
}
_CONSTRAINT_EXPR_KEYS = ("require", "expr", "when", "then")


def _project_constraints(value: Any, ctx: _Ctx) -> Any:
    """Constraint definitions: ids validated, caller error messages dropped (the server
    generates ``"... constraint <id> violated"``), expressions comment-free with identifier-only
    string literals, and every unknown key dropped."""
    if value is None:
        return None
    if not isinstance(value, dict):
        raise MetadataContractViolation
    out: dict[str, Any] = {}
    for group in ("structural", "derived"):
        entries = value.get(group)
        if entries is None:
            continue
        if not isinstance(entries, list):
            raise MetadataContractViolation
        cleaned: list[Any] = []
        for entry in entries:
            if not isinstance(entry, dict):
                raise MetadataContractViolation
            new_entry: dict[str, Any] = {}
            if entry.get("id") is not None:
                new_entry["id"] = _strict_id(entry["id"], ctx)
            for key in _CONSTRAINT_EXPR_KEYS:
                if key in entry and entry[key] is not None:
                    if not expression_is_closed(entry[key]):
                        raise MetadataContractViolation
                    new_entry[key] = entry[key]
            cleaned.append(new_entry)
        out[group] = cleaned
    return out


def _project_objectives(value: Any, ctx: _Ctx) -> Any:
    """Objectives are rebuilt from known fields (``unit`` limited to a closed vocabulary or a
    short identifier). An accepted objective must keep its score, so names obey the SAME rule the
    result projectors use for metric keys (``METRIC_KEY_RE``): anything else is refused."""
    for name in declared_metric_names(value):
        if METRIC_KEY_RE.fullmatch(name) is None:
            raise MetadataContractViolation
    if not isinstance(value, (list, dict)):
        return value  # shape errors are the service's existing 400
    try:
        return _OBJECTIVES(value, ctx, 0)
    except _Drop:
        raise MetadataContractViolation from None


