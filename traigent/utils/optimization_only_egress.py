def project_for_phase(
    phase: str,
    payload: Any,
    *,
    declared: Iterable[str] | None = None,
    session_id: str | None = None,
) -> Any:
    """Project ``payload`` for ``phase`` unconditionally. Returns a new object; the input is
    never mutated. Raises :class:`MetadataContractViolation` for a payload the server would
    refuse, and ``ValueError`` for an unknown phase (an unclassified send must not happen)."""
    detached = copy.deepcopy(payload)
    if phase == PHASE_SESSION_CREATE_AUTO:
        return project_session_create_auto(detached)
    projector = _PROJECTORS.get(phase)
    if projector is None:
        raise ValueError(f"unknown optimization_only egress phase: {phase!r}")
    names = tuple(declared) if declared is not None else declared_for(session_id)
    return projector(detached, names)


def project_for_send(
    phase: str,
    payload: Any,
    *,
    explicit: bool | Policy | None = None,
    declared: Iterable[str] | None = None,
    session_id: str | None = None,
) -> Any:
    """The call every send boundary makes right before transmission.

    Mode off: returns ``payload`` itself, untouched (legacy behaviour). Mode on: returns a
    detached projected copy that the caller sends and reuses across retries.
    """
    if not is_active(explicit):
        return payload
    if phase in (
        PHASE_SESSION_CREATE,
        PHASE_SESSION_CREATE_LEGACY,
        PHASE_SESSION_CREATE_AUTO,
    ):
        if _payload_embeds_examples(payload):
            raise OptimizationOnlyRefusal("embedded_examples")
    return project_for_phase(phase, payload, declared=declared, session_id=session_id)


def refuse_if_active(operation: str, *, explicit: bool | Policy | None = None) -> None:
    """Raise :class:`OptimizationOnlyRefusal` before any transport call when the mode is on.

    Used for dataset/example uploads, hosted LLM / hosted agent execution and trace export.
    """
    if is_active(explicit):
        raise OptimizationOnlyRefusal(operation)


def refuse_embedded_examples(
    payload: Any, *, explicit: bool | Policy | None = None
) -> None:
    """Refuse (locally) a body that embeds example/dataset text when the mode is on."""
    if is_active(explicit) and _payload_embeds_examples(payload):
        raise OptimizationOnlyRefusal("embedded_examples")
