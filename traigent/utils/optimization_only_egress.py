class MetadataContractViolation(ValueError):
    """A flagged tenant's request broke the metadata contract. Carries no request data."""

    error_code = OPTIMIZATION_ONLY_METADATA_INVALID
    status_code = 400

    def __init__(self) -> None:
        super().__init__(OPTIMIZATION_ONLY_METADATA_INVALID_MESSAGE)


# ---------------------------------------------------------------------------------------
# Schema engine. A spec is ``f(value, ctx, depth) -> projected`` raising ``_Drop`` when the
# value does not fit (the caller decides: optional fields are dropped, ``strict`` ones reject).
# ---------------------------------------------------------------------------------------


class _Drop(Exception):  # noqa: N818 - control flow, not an error type
    pass


class _Ctx:
    __slots__ = ("allowed_metrics",)

    def __init__(self, declared: Iterable[str] = ()) -> None:
        names = {
            n for n in declared if isinstance(n, str) and METRIC_KEY_RE.fullmatch(n)
        }
        self.allowed_metrics: frozenset[str] = STANDARD_METRIC_KEYS | frozenset(names)


Spec = Callable[[Any, _Ctx, int], Any]


def _is_number(value: Any) -> bool:
    return isinstance(value, (int, float)) and not isinstance(value, bool)


def s_int(lo: int = 0, hi: int = 2**53) -> Spec:
    def spec(value: Any, _c: _Ctx, _d: int) -> Any:
        if (
            isinstance(value, bool)
            or not isinstance(value, int)
            or not lo <= value <= hi
        ):
            raise _Drop
        return value

    return spec


def s_num(lo: float = -MAX_NUM, hi: float = MAX_NUM) -> Spec:
    def spec(value: Any, _c: _Ctx, _d: int) -> Any:
        if not _is_number(value) or not math.isfinite(value) or not lo <= value <= hi:
            raise _Drop
        return value

    return spec


def s_bool(value: Any, _c: _Ctx, _d: int) -> Any:
    if not isinstance(value, bool):
        raise _Drop
    return value


def s_false(value: Any, _c: _Ctx, _d: int) -> Any:
    if value is not False:
        raise _Drop
    return value


def s_ts(value: Any, _c: _Ctx, _d: int) -> Any:
    if not isinstance(value, str) or not 10 <= len(value) <= 64:
        raise _Drop
    try:
        _ = datetime.fromisoformat(value.replace("Z", "+00:00"))
    except ValueError:
        raise _Drop from None
    return value


def _s_regex(pattern: re.Pattern[str]) -> Spec:
    def spec(value: Any, _c: _Ctx, _d: int) -> Any:
        if not isinstance(value, str) or pattern.fullmatch(value) is None:
            raise _Drop
        return value

    return spec


