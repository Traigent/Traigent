def token(prefix: str, original: str) -> str:
    """Deterministic identifier for a non-identifier-shaped identity string.

    The same original always yields the same token (grouping stays stable across runs) and
    the token reveals nothing about the original beyond its sha256 prefix.
    """
    return f"{prefix}_{hashlib.sha256(original.encode('utf-8')).hexdigest()[:16]}"


def s_tok(prefix: str) -> Spec:
    """An identity string: kept verbatim when identifier-shaped, else its deterministic token.

    Only a structurally invalid value (not a non-empty string) is refused.
    """

    def spec(value: Any, _c: Any, _d: int) -> Any:
        if not isinstance(value, str) or not value.strip():
            raise _Drop
        return value if ID_RE.fullmatch(value) else token(prefix, value)

    return spec


def s_enum(*allowed: str) -> Spec:
    allowed_set = frozenset(allowed)

    def spec(value: Any, _c: _Ctx, _d: int) -> Any:
        if not isinstance(value, str) or value not in allowed_set:
            raise _Drop
        return value

    return spec


def s_null(inner: Spec) -> Spec:
    def spec(value: Any, ctx: _Ctx, depth: int) -> Any:
        return None if value is None else inner(value, ctx, depth)

    return spec


def s_any_of(*specs: Spec) -> Spec:
    def spec(value: Any, ctx: _Ctx, depth: int) -> Any:
        for candidate in specs:
            try:
                return candidate(value, ctx, depth)
            except _Drop:
                continue
        raise _Drop

    return spec


def s_obj(fields: dict[str, Spec], *, strict_keys: Iterable[str] = ()) -> Spec:
    """Rebuild a mapping from ``fields``; unknown keys are dropped.

    A key in ``strict_keys`` that is present but malformed rejects the whole request.
    """
    strict = frozenset(strict_keys)

    def spec(value: Any, ctx: _Ctx, depth: int) -> Any:
        if depth > MAX_DEPTH or not isinstance(value, dict):
            raise _Drop
        out: dict[str, Any] = {}
        for key, inner in fields.items():
            if key not in value:
                continue
            try:
                out[key] = inner(value[key], ctx, depth + 1)
            except _Drop:
                if key in strict:
                    raise MetadataContractViolation from None
        return out

    return spec


def s_list(inner: Spec, *, max_len: int = MAX_LIST, strict_len: bool = False) -> Spec:
    def spec(value: Any, ctx: _Ctx, depth: int) -> Any:
        if depth > MAX_DEPTH or not isinstance(value, (list, tuple)):
            raise _Drop
        if strict_len and len(value) > max_len:
            raise MetadataContractViolation
        out: list[Any] = []
        for item in list(value)[:max_len]:
            try:
                out.append(inner(item, ctx, depth + 1))
            except _Drop:
                continue
        return out

    return spec


def s_map(key_spec: Spec, inner: Spec, *, max_len: int = MAX_LIST) -> Spec:
    def spec(value: Any, ctx: _Ctx, depth: int) -> Any:
        if depth > MAX_DEPTH or not isinstance(value, dict):
            raise _Drop
        out: dict[str, Any] = {}
        for key, item in list(value.items())[:max_len]:
            try:
                key_spec(key, ctx, depth)
                out[key] = inner(item, ctx, depth + 1)
            except _Drop:
                continue
        return out

    return spec


def _metric_key(key: Any, ctx: _Ctx, _d: int) -> Any:
    if not isinstance(key, str) or key not in ctx.allowed_metrics:
        raise _Drop
    return key


def s_metric_map(inner: Spec | None = None, *, max_len: int = 64) -> Spec:
    """A mapping whose keys must be declared (or standard) metric names."""
    return s_map(_metric_key, inner or s_null(s_num()), max_len=max_len)


def s_metric_name(value: Any, ctx: _Ctx, depth: int) -> Any:
    return _metric_key(value, ctx, depth)


def s_closed_tree(value: Any, _c: _Ctx, depth: int) -> Any:
    """Generic closed-leaf tree (content identity): keys are identifiers; leaves are numbers,
    booleans, digests or identifiers. Any other string leaf is dropped."""
    if depth > MAX_DEPTH:
        raise _Drop
    if value is None or isinstance(value, bool):
        return value
    if _is_number(value):
        if not math.isfinite(value) or abs(value) > MAX_NUM:
            raise _Drop
        return value
    if isinstance(value, str):
        if SHA256_RE.fullmatch(value) or ID_RE.fullmatch(value):
            return value
        raise _Drop
    if isinstance(value, (list, tuple)):
        out_list: list[Any] = []
        for item in list(value)[:MAX_LIST]:
            try:
                out_list.append(s_closed_tree(item, _c, depth + 1))
            except _Drop:
                continue
        return out_list
    if isinstance(value, dict):
        out: dict[str, Any] = {}
        for key, item in list(value.items())[:MAX_LIST]:
            if not isinstance(key, str) or ID_RE.fullmatch(key) is None:
                continue
            try:
                out[key] = s_closed_tree(item, _c, depth + 1)
            except _Drop:
                continue
        return out
    raise _Drop


