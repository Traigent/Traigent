"""SDK-side egress projector for ``optimization_only`` workspaces.

A faithful, dependency-free port of the backend's closed metadata contract
(TraigentBackend ``src/services/optimization_only_metadata_contract.py``,
``METADATA_CONTRACT_VERSION = 1``, pinned at backend commit ``2d5cceda5``). For an
``optimization_only`` tenant the server REBUILDS optimization-loop metadata from a closed
per-phase schema and refuses trace / dataset / hosted-LLM operations. This module lets the
SDK apply the same projection locally, at the last moment before a payload is handed to a
transport, so content the server would drop or refuse never leaves the machine.

The first half of this file (everything up to the ``SDK layer`` banner) is a verbatim port of
the backend projector semantics: same identifier regexes, same tokenization
(``fn_``/``ak_``/``ds_``/``ev_``/``es_``/``dn_``/``cc_``/``cr_`` + first 16 hex of sha256),
same objective-aware metric rules, limits and refusals. The only differences are that the
Flask response helpers and the database-backed tenant guard are removed (this module has no
network, Flask or database imports) and the violation is a local exception. Do not "improve"
the ported half: parity with the backend is asserted against fixtures generated by running
the backend module itself (``tests/fixtures/optimization_only_parity``).

The second half adds what only the SDK needs: the opt-in mode switch
(``TRAIGENT_OPTIMIZATION_ONLY`` or an explicit ``optimization_only`` argument, plus a latch
set by a closed ``403 optimization_only``), phase dispatch for each send boundary, a
per-session record of declared objectives, and refusal of operations the server forbids.

The mode is OPT-IN: when it is not enabled every function here that sits on a send path is a
no-op that returns its input unchanged.
"""

