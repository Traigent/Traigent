def outgoing_may_be_active(explicit: bool | Policy | None = None) -> bool:
    """Cheap pre-check for the transport hook: False means "nothing to enforce, add no work".

    True when the client opted in outright, any credential scope is latched, or the
    environment opts in.
    """
    if isinstance(explicit, Policy):
        explicit = explicit.explicit
    if explicit is True or _latched_scopes:
        return True
    return env_setting() is True


def _canonical(value: Any) -> str:
    return json.dumps(value, sort_keys=True, separators=(",", ":"), allow_nan=True)


def _is_fixed_point(phase: str, body: Any, session_id: str | None) -> bool:
    try:
        projected = project_for_phase(phase, body, session_id=session_id)
    except (MetadataContractViolation, ValueError):
        return False
    if (
        phase in (PHASE_SESSION_CREATE_AUTO, PHASE_SESSION_CREATE)
        and isinstance(body, dict)
        and isinstance(projected, dict)
        and re.fullmatch(r"cr_[0-9a-f]{16}", str(body.get("code_revision", "")))
    ):
        # A ``code_revision`` label tokenizes to ``cr_<hash>``, which is not revision-shaped,
        # so projecting it again re-tokenizes (a backend property): ignore that one field.
        body = {k: v for k, v in body.items() if k != "code_revision"}
        projected = {k: v for k, v in projected.items() if k != "code_revision"}
    return _canonical(projected) == _canonical(body)


def _api_tails(path: str, prefixes: Iterable[str]) -> list[str]:
    """Candidate route parts of ``path``: after each configured API base the client holds
    (``/proxy/api/v1`` style), after the default ``/api/vN``, and the path itself."""
    tails: list[str] = []
    for prefix in sorted({p.rstrip("/") for p in prefixes if p}, key=len, reverse=True):
        if path == prefix or path.startswith(prefix + "/"):
            tails.append(path[len(prefix) :] or "/")
    match = _DEFAULT_API_PREFIX.match(path)
    if match:
        tails.append(path[match.end() :] or "/")
    tails.append(path)
    return tails


def _reject_duplicates(pairs: list[tuple[str, Any]]) -> dict[str, Any]:
    out: dict[str, Any] = {}
    for key, value in pairs:
        if key in out:
            raise ValueError("duplicate JSON member")
        out[key] = value
    return out


def _refuse_constant(_name: str) -> Any:
    raise ValueError("non-finite JSON constant")


def loads_strict(body: bytes | bytearray | str) -> Any:
    """Parse a request body exactly as a server would see it: UTF-8, no duplicate object
    members at any depth, no NaN/Infinity. Raises ``ValueError`` otherwise."""
    text = bytes(body).decode("utf-8") if isinstance(body, (bytes, bytearray)) else body
    return json.loads(
        text, object_pairs_hook=_reject_duplicates, parse_constant=_refuse_constant
    )


def canonical_json_bytes(value: Any) -> bytes:
    """The one serialisation transmitted for a validated body (what was judged is sent)."""
    return json.dumps(value, separators=(",", ":"), allow_nan=False).encode("utf-8")


_TOKEN_RE = re.compile(r"^[\x21-\x7e]{1,4096}$")
_EMAIL_RE = re.compile(r"^[^\s@]{1,128}@[^\s@]{1,255}$")
_SCOPE_RE = re.compile(r"^[A-Za-z0-9_.:/ -]{0,256}$")
_GRANT_TYPES = frozenset(
    {"client_credentials", "refresh_token", "password", "authorization_code"}
)


def _auth_value_ok(field: str, value: Any) -> bool:
    if not isinstance(value, str):
        return False
    if field == "email":
        return _EMAIL_RE.fullmatch(value) is not None
    if field == "grant_type":
        return value in _GRANT_TYPES
    if field == "scope":
        return _SCOPE_RE.fullmatch(value) is not None
    if field == "password":
        return 1 <= len(value) <= 1024 and value.isprintable()
    return _TOKEN_RE.fullmatch(value) is not None


def _auth_body_ok(path_tail: str, body: Any) -> bool:
    fields = next(
        (
            f
            for route, f in AUTH_FIELDS.items()
            if path_tail.rstrip("/").endswith("/" + route)
        ),
        None,
    )
    if fields is None or body is UNREADABLE_BODY:
        return False
    parsed = body
    if isinstance(body, (bytes, bytearray, str)):
        try:
            parsed = loads_strict(body)
        except ValueError:
            from urllib.parse import parse_qsl

            try:
                text = (
                    bytes(body).decode("utf-8")
                    if isinstance(body, (bytes, bytearray))
                    else body
                )
            except UnicodeDecodeError:
                return False
            pairs = parse_qsl(text, keep_blank_values=True)
            if len({k for k, _ in pairs}) != len(pairs):
                return False  # duplicate form field
            parsed = dict(pairs)
    return (
        isinstance(parsed, dict)
        and set(parsed) <= fields
        and all(_auth_value_ok(k, v) for k, v in parsed.items())
    )


_INACTIVE = object()


def enforce_outgoing(
    method: str,
    url: Any,
    headers: Any,
    body: Any,
    *,
    explicit: bool | Policy | None = None,
    api_prefixes: Iterable[str] = (),
) -> bytes | None:
    """Judge one request (see :func:`_judge_outgoing`); raise to refuse.

    Returns ``None`` normally. When the body arrived as bytes/str and was validated as JSON,
    returns its CANONICAL serialisation: the caller should transmit that, so exactly what was
    judged (duplicate members refused, one canonical encoding) is what is sent.
    """
    parsed = _judge_outgoing(
        method, url, headers, body, explicit=explicit, api_prefixes=api_prefixes
    )
    if (
        parsed is _INACTIVE
        or parsed is None
        or not isinstance(body, (bytes, bytearray, str))
    ):
        return None
    return canonical_json_bytes(parsed)


def _judge_outgoing(
    method: str,
    url: Any,
    headers: Any,
    body: Any,
    *,
    explicit: bool | Policy | None = None,
    api_prefixes: Iterable[str] = (),
) -> Any:
    """Transport backstop for one request (FINAL url/headers/body).

    Mode inactive for the request's credential: returns at once. Mode active: DEFAULT-DENY.
    The path must be free of dot segments and percent-encoded separators, every segment must
    be identifier-shaped once decoded, and the route (after the client's API base) must be in
    :data:`ALLOWED_ROUTES`. A body route passes only if its JSON body is a fixed point of its
    phase projector (Director bodies must match their allowlist, auth bodies carry credential
    fields only); query values must be identifier-shaped. Anything else raises
    :class:`OptimizationOnlyRefusal` before a byte is sent.
    """
    headers_scope = credential_scope(url, headers) if scope_required(None) else None
    base = explicit.explicit if isinstance(explicit, Policy) else explicit
    if not is_active(Policy(base, headers_scope)):
        return _INACTIVE
    from urllib.parse import parse_qsl, unquote

    parts = urlsplit(str(url))
    raw_path = parts.path
    if (
        "\\" in raw_path
        or _BAD_PATH_ESCAPES.search(raw_path)
        or "//" in raw_path.rstrip("/")
        or any(seg in (".", "..") for seg in raw_path.split("/"))
    ):
        raise OptimizationOnlyRefusal("path_not_normalised")
    verb = str(method).upper()
    tail = ""
    route = None
    for candidate in _api_tails(raw_path, api_prefixes):
        route = next(
            (
                r
                for r in ALLOWED_ROUTES
                if r.method == verb and r.pattern.match(candidate)
            ),
            None,
        )
        if route is not None:
            tail = candidate
            break
    if route is None:
        raise OptimizationOnlyRefusal("route_not_allowed")
    for segment in tail.split("/"):
        if segment and ID_RE.fullmatch(unquote(segment)) is None:
            raise OptimizationOnlyRefusal("path_parameter_not_closed")
    for key, value in parse_qsl(parts.query, keep_blank_values=True):
        if ID_RE.fullmatch(key) is None or (value and ID_RE.fullmatch(value) is None):
            raise OptimizationOnlyRefusal("query_not_closed")
    has_body = body is not None and body != b"" and body != ""
    if route.kind == "read":
        if has_body:
            raise OptimizationOnlyRefusal("body_not_allowed")
        return None
    if route.kind == "auth":
        if not _auth_body_ok(tail, body):
            raise OptimizationOnlyRefusal("auth_body_not_closed")
        return None
    if body is UNREADABLE_BODY:
        raise OptimizationOnlyRefusal("body_unreadable")
    parsed = body
    if isinstance(body, (bytes, bytearray, str)):
        try:
            parsed = loads_strict(body) if body else None
        except ValueError:
            raise OptimizationOnlyRefusal("body_not_json") from None
    if route.kind == "director":
        allowed = (
            DIRECTOR_CREATE_ALLOWLIST
            if tail.rstrip("/").endswith("/director/sessions")
            else DIRECTOR_TURN_ALLOWLIST
        )
        if not _director_conforms(parsed, allowed):
            raise OptimizationOnlyRefusal("director_request")
        return parsed
    if route.phase is None:
        return parsed
    if not isinstance(parsed, (dict, list)):
        raise OptimizationOnlyRefusal("body_missing")
    session_id = session_id_from_url(tail)
    if route.phase == PHASE_OPTIMIZER_METRICS:
        segs = tail.rstrip("/").split("/")
        session_id = segs[-2] if segs[-1] == "batch" else segs[-1]
        if isinstance(parsed, dict) and "submissions" in parsed:
            if set(parsed) != {"submissions"} or not isinstance(
                parsed["submissions"], list
            ):
                raise OptimizationOnlyRefusal("body_not_projected")
            items = parsed["submissions"]
        else:
            items = [parsed]
        if not all(_is_fixed_point(route.phase, item, session_id) for item in items):
            raise OptimizationOnlyRefusal("body_not_projected")
        return parsed
    if not _is_fixed_point(route.phase, parsed, session_id):
        raise OptimizationOnlyRefusal("body_not_projected")
    if route.phase == PHASE_SESSION_CREATE_AUTO and _payload_embeds_examples(parsed):
        raise OptimizationOnlyRefusal("embedded_examples")
    return parsed


